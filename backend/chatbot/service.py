def generate_chatbot_response(user_message, db_context, user_role):
    """
    Sends context + query to AI provider (Gemini / OpenAI API).
    Falls back gracefully to intelligent context parser if API key is not configured or fails.
    """
    api_key = os.environ.get('GEMINI_API_KEY') or os.environ.get('AI_API_KEY') or os.environ.get('GOOGLE_API_KEY')
    openai_key = os.environ.get('OPENAI_API_KEY')

    prompt = f"USER ROLE: {user_role.upper()}\n\nAUTHORIZED NEXORA DATABASE CONTEXT:\n{db_context}\n\nUSER QUESTION: {user_message}"

    if api_key:
        try:
            return call_gemini_api(api_key, SYSTEM_PROMPT, prompt)
        except Exception as e:
            print(f"[Chatbot Service] Gemini API call error: {e}. Falling back to fallback engine.")

    if openai_key:
        try:
            return call_openai_api(openai_key, SYSTEM_PROMPT, prompt)
        except Exception as e:
            print(f"[Chatbot Service] OpenAI API call error: {e}. Falling back to fallback engine.")

    # Intelligent Fallback Engine using actual DB context text
    return generate_fallback_response(user_message, db_context, user_role)


def call_gemini_api(api_key, system_instruction, prompt_text):
    """Calls Google Gemini REST API using standard urllib."""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
    headers = {"Content-Type": "application/json"}
    
    payload = {
        "contents": [
            {
                "role": "user",
                "parts": [{"text": f"{system_instruction}\n\n{prompt_text}"}]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 1000
        }
    }
    
    req = urllib.request.Request(url, data=json.dumps(payload).encode('utf-8'), headers=headers)
    with urllib.request.urlopen(req, timeout=12) as response:
        res_data = json.loads(response.read().decode('utf-8'))
        candidates = res_data.get('candidates', [])
        if candidates and 'content' in candidates[0]:
            parts = candidates[0]['content'].get('parts', [])
            if parts:
                return parts[0].get('text', '')
    raise Exception("Empty response from Gemini API")


def call_openai_api(api_key, system_instruction, prompt_text):
    """Calls OpenAI REST API using standard urllib."""
    url = "https://api.openai.com/v1/chat/completions"
    headers = {
        "Content-Type": "application/json",
        "Authorization": f"Bearer {api_key}"
    }
    
    payload = {
        "model": "gpt-4o-mini",
        "messages": [
            {"role": "system", "content": system_instruction},
            {"role": "user", "content": prompt_text}
        ],
        "temperature": 0.2
    }
    
    req = urllib.request.Request(url, data=json.dumps(payload).encode('utf-8'), headers=headers)
    with urllib.request.urlopen(req, timeout=12) as response:
        res_data = json.loads(response.read().decode('utf-8'))
        choices = res_data.get('choices', [])
        if choices:
            return choices[0]['message']['content']
    raise Exception("Empty response from OpenAI API")


